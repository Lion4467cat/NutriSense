"""Recipe-table access + the invisible-component distribution rule (07d).

The table `data/indb_recipes.yaml` is generated by
`tools/import_indb_recipes.py` from the INDB capstone files (use-with-
citation; regenerated from source, never bundled raw). This module is the
only seam the serving path needs for it:

- `load_recipes()` — cached table access.
- `recipe_nutrients_per_100g(code)` — kcal/protein for the S5 verdict path.
- `distribute_invisible(visible, recipe_entry)` — the method-doc section 7
  rule materialized: non-segmentable recipe mass (oil/ghee/spices/salt/
  cooking water, `visible: false` in the table) is distributed over the
  visible carriers proportional to their measured grams. Call it with the
  measured visible carrier masses; it returns the mass-portion dict the
  S4 grams path should consume.
"""
from __future__ import annotations

from pathlib import Path

import yaml

INDB_PATH = Path("data") / "indb_recipes.yaml"
_CACHE: dict[str, dict] = {}


def load_recipes() -> dict:
    if "recipes" not in _CACHE:
        with open(INDB_PATH) as f:
            _CACHE["recipes"] = yaml.safe_load(f)
    return _CACHE["recipes"]


def recipe_entry(code: str) -> dict | None:
    return load_recipes()["recipes"].get(code)


def recipe_nutrients_per_100g(code: str) -> dict | None:
    entry = recipe_entry(code)
    return None if entry is None else entry["per_100g"]


def invisible_ports(recipe_entry: dict) -> tuple[float, float, float]:
    """(invisible_resolved_g, visible_resolved_g, resolved_total_g)."""
    m = recipe_entry["mass_audit_g"]
    return (m["invisible_resolved"], m["visible_resolved"],
            m["resolved_total"])


def distribute_invisible(visible: dict[str, float],
                         entry: dict) -> dict[str, float]:
    """Spread the recipe's invisible resolved mass over visible carriers.

    visible: measured visible carrier masses (any keys). Amounts are
    preserved in total mass: every visible carrier keeps its relative share,
    and the total grows by the recipe's invisible-resolved mass. Invisible
    mass scales each visible component by (1 + invisible/visible). Only the
    gram-resolved part of the recipe (mass_audit_g) is used — unresolved
    tsp/cup rows contribute nothing here, which is what the resolved-mass
    audit is for.
    """
    total_visible = sum(v for v in visible.values() if v is not None)
    if not visible or total_visible <= 0:
        return dict(visible)
    inv_g, vis_g, _ = invisible_ports(entry)
    if vis_g <= 0 or inv_g <= 0:
        return dict(visible)
    inflate = 1.0 + inv_g / vis_g
    return {k: v * inflate for k, v in visible.items()}
