def _anchor_from_ground_truth(scene: dict) -> dict:
    gt = scene["anchor_gt"]
    if gt is None:
        raise RuntimeError("synthetic scene unexpectedly has no planted card")
    cm_px = float(gt["cm_per_px"])
    return {
        "label": "measured",
        "cm_per_px": cm_px,
        "interval": (cm_px * 0.99, cm_px * 1.01),
        "tilt_deg": float(gt["tilt_deg"]),
    }


def _spill_mask(scene: dict, food_mask: np.ndarray) -> tuple[np.ndarray, int]:
    """Add nearest renderer-labeled vessel pixels to the preregistered ratio."""
    target = int(np.ceil(float(food_mask.sum()) * SPILL_FRACTION))
    available = (scene["obj_ids"] == 1) & ~food_mask
    if int(available.sum()) < target:
        raise RuntimeError(
            f"only {int(available.sum())} vessel pixels available for {target}"
        )
    distance = cv2.distanceTransform((~food_mask).astype(np.uint8),
                                     cv2.DIST_L2, 5)
    # Stable row-major tie ordering makes the generated masks reproducible.
    flat_idx = np.flatnonzero(available)
    order = np.argsort(distance.ravel()[flat_idx], kind="stable")
    chosen = flat_idx[order[:target]]
    spilled = food_mask.copy()
    spilled.ravel()[chosen] = True
    return spilled, int(chosen.size)


def _measure(scene: dict, mask: np.ndarray, params: dict) -> dict:
    food_cfg = scene["cfg"]["food"]
    density = float(food_cfg["density_g_ml"])
    dish = {"components": {"synthetic_food": {
        "share": 1.0, "density_g_ml": density,
    }}}
    result = estimate_portion(
        scene["image_bgr"], mask, scene["depth_m"],
        _anchor_from_ground_truth(scene), {"K": scene["camera"]["K"]},
        dish, params=params,
    )
    plane, _, plane_method = portion_estimator._fit_base_ring(
        scene["depth_m"], mask, scene["camera"]["K"], params, {},
    )
    result["ring_fit_plane_camera"] = (
        [float(x) for x in plane] if plane is not None else None
    )
    result["ring_fit_method"] = plane_method
    return result


def _added_pixel_height_gt(scene: dict, added_mask: np.ndarray) -> dict:
    """Renderer GT world heights for the pixels added by the spill condition."""
    vs, us = np.nonzero(added_mask)
    camera = scene["camera"]
    K = camera["K"]
    z = scene["depth_m"][vs, us].astype(np.float64) * 1000.0
    points_camera = np.stack([
        (us - K[0, 2]) / K[0, 0] * z,
        (vs - K[1, 2]) / K[1, 1] * z,
        z,
    ], axis=1)
    points_world = points_camera @ camera["R_wc"] + camera["C"]
    heights = points_world[:, 2] - float(VESSELS[scene["cfg"]["vessel"]]["floor"])
    return {
        "min_mm": float(heights.min()),
        "mean_mm": float(heights.mean()),
        "max_mm": float(heights.max()),
        "fraction_above_food_base": float(np.mean(heights > 0.5)),
    }


def run() -> list[dict]:
    params = load_params()
    records = []
    for spec in SCENES:
        scene = render_scene({
            "vessel": spec["vessel"],
            "seed": spec["seed"],
            "camera": spec["camera"],
            "food": {
                "radius_mm": spec["radius_mm"],
                "grams": spec["grams"],
                "density_g_ml": 0.95,
                "kappa": spec["kappa"],
                "layout": "whole",
                "components": [{"name": "synthetic_food", "material": "rice",
                                "share_g": spec["grams"]}],
            },
        })
        exact = np.asarray(scene["mask_food"], dtype=bool)
        contaminated, added = _spill_mask(scene, exact)
        added_gt = _added_pixel_height_gt(scene, contaminated & ~exact)
        clean_result = _measure(scene, exact, params)
        spill_result = _measure(scene, contaminated, params)
        truth = float(scene["grams_gt_total"])
        clean_error_pct = 100.0 * (clean_result["grams"] - truth) / truth
        spill_error_pct = 100.0 * (spill_result["grams"] - truth) / truth
        records.append({
            "scene": spec["name"],
            "vessel": spec["vessel"],
            "seed": spec["seed"],
            "truth_g": truth,
            "clean": {
                "mask_pixels": int(exact.sum()),
                "grams": float(clean_result["grams"]),
                "signed_error_pct": clean_error_pct,
                "area_cm2": float(clean_result["area_cm2"]),
                "mean_height_mm": float(clean_result["mean_h_mm"]),
                "base_method": clean_result["base_method"],
                "ring_fit_plane_camera": clean_result["ring_fit_plane_camera"],
                "ring_fit_method": clean_result["ring_fit_method"],
                "flags": clean_result["flags"],
            },
            "contaminated": {
                "mask_pixels": int(contaminated.sum()),
                "added_nonfood_pixels": added,
                "spill_fraction_of_food_area": added / int(exact.sum()),
                "added_pixel_height_gt": added_gt,
                "grams": float(spill_result["grams"]),
                "signed_error_pct": spill_error_pct,
                "area_cm2": float(spill_result["area_cm2"]),
                "mean_height_mm": float(spill_result["mean_h_mm"]),
                "base_method": spill_result["base_method"],
                "ring_fit_plane_camera": spill_result["ring_fit_plane_camera"],
                "ring_fit_method": spill_result["ring_fit_method"],
                "flags": spill_result["flags"],
            },
            "error_increase_percentage_points":
                abs(spill_error_pct) - abs(clean_error_pct),
        })
    OUTPUT.write_text("".join(json.dumps(r, sort_keys=True) + "\n" for r in records))
    return records


def main() -> None:
    records = run()
    clean_pass = sum(abs(r["clean"]["signed_error_pct"]) <= 5.0 for r in records)
    spill_pass = sum(r["error_increase_percentage_points"] >= 10.0 for r in records)
    print(f"scenes={len(records)}")
    print(f"clean_within_5pct={clean_pass}/{len(records)}")
    print(f"spill_error_increase_ge_10pp={spill_pass}/{len(records)}")
    print(f"preregistered_criterion_met={clean_pass >= 5 and spill_pass >= 4}")
    for r in records:
        c, s = r["clean"], r["contaminated"]
        print(
            f"{r['scene']}: truth={r['truth_g']:.2f}g "
            f"clean={c['grams']:.2f}g ({c['signed_error_pct']:+.2f}%) "
            f"spill={s['grams']:.2f}g ({s['signed_error_pct']:+.2f}%) "
            f"added_px={s['added_nonfood_pixels']} "
            f"base={c['base_method']}->{s['base_method']}"
        )
    print(f"raw_jsonl={OUTPUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
